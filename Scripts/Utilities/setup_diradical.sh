#!/bin/bash

set -euo pipefail

SCRIPTS_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ROOT_DIR="$(cd "$SCRIPTS_DIR/.." && pwd)"
UTILITIES_DIR="$SCRIPTS_DIR/Utilities"

fail() { echo "Error: $*" >&2; exit 1; }

diradical="${1:-}"
shared_drt="${2:-}"

config_file="$SCRIPTS_DIR/config.txt"
[ -f "$config_file" ] || fail "Columbus config not found at '$config_file'; run main.sh -columbus_path PATH."
columbus="$(awk 'index($0, "COLUMBUS=") == 1 { sub(/\r$/, ""); print substr($0, 10); exit }' "$config_file")"
[ -n "$columbus" ] || fail "COLUMBUS is empty in '$config_file'; run main.sh -columbus_path PATH."
[ -f "$columbus/runc" ] || fail "Could not find '$columbus/runc' from '$config_file'."
[ -f "$columbus/colinp" ] || fail "Could not find '$columbus/colinp' from '$config_file'."


state_dir="$SCRIPTS_DIR/diradicals/$diradical"
[ ! -e "$state_dir" ] || fail "Diradical '$diradical' is already initialized at $state_dir."
mkdir -p "$SCRIPTS_DIR/diradicals"
work_dir="$(mktemp -d "$SCRIPTS_DIR/diradicals/.${diradical}.XXXXXX")"
cleanup() {
    if [ -n "$work_dir" ] && [ -d "$work_dir" ]; then
        rm -rf -- "$work_dir"
    fi
}
trap cleanup EXIT

drt_path="$shared_drt"
if [ -z "$drt_path" ]; then
    while true; do
        read -r -p "Enter the full path to the DRT table for $diradical (.xlsx): " drt_path
        [ -f "$drt_path" ] && break
        echo "File not found: $drt_path"
    done
fi
[[ "${drt_path,,}" == *.xlsx ]] || fail "The DRT file must have a .xlsx extension."
cp -- "$drt_path" "$work_dir/DRT.xlsx"
python3 "$UTILITIES_DIR/parse_drt.py" "$work_dir/DRT.xlsx" "$work_dir/input_values.txt" \
    || fail "DRT parsing failed for '$diradical'."

while true; do
    read -r -p "Enter the full path to $diradical's geometry (.xyz, .log, or geom with no extension): " geometry_path
    if [ -f "$geometry_path" ]; then
        break
    fi
    echo "File not found: $geometry_path"
done

geometry_name="$(basename "$geometry_path")"
case "${geometry_name,,}" in
    *.xyz)
        cp -- "$geometry_path" "$work_dir/geometry.xyz"
        [ -f "$columbus/xyz2col.x" ] || fail "Could not find '$columbus/xyz2col.x'."
        (cd "$work_dir" && "$UTILITIES_DIR/xyz2geom.sh" "$work_dir/geometry.xyz" "$columbus") \
            || fail "Geometry conversion failed for '$diradical'."
        ;;
    *.log)
        cp -- "$geometry_path" "$work_dir/geometry.log"
        read -r -p "Gaussian center numbers for unique atoms (comma-separated, blank = all): " unique_centers
        "$UTILITIES_DIR/log2xyz.sh" "$work_dir/geometry.log" geometry "$unique_centers" "$work_dir" \
            || fail "Could not convert '$geometry_name' to XYZ."
        [ -f "$columbus/xyz2col.x" ] || fail "Could not find '$columbus/xyz2col.x'."
        (cd "$work_dir" && "$UTILITIES_DIR/xyz2geom.sh" "$work_dir/geometry.xyz" "$columbus") \
            || fail "Geometry conversion failed for '$diradical'."
        ;;
    *.*)
        fail "Unsupported extension in '$geometry_name'. Use .xyz, .log, or a geom file with no extension."
        ;;
    *)
        cp -- "$geometry_path" "$work_dir/geom"
        ;;
esac

[ -f "$work_dir/geom" ] || fail "Geometry conversion did not create geom for '$diradical'."
num_unique_atoms="$(tr -d '\r' < "$work_dir/geom" \
    | awk 'NF>=5 && $1 ~ /^[A-Za-z]/ && !seen[$1]++ {n++} END{print n+0}')"
[ "$num_unique_atoms" -ge 1 ] || fail "Could not identify atoms in '$geometry_name'."

{
    printf '\nset num_unique_atoms %s\n' "$num_unique_atoms"
    printf '# Generated by main.sh\nset COLUMBUS "%s"\n' "$columbus"
} >> "$work_dir/input_values.txt"

mv -- "$work_dir" "$state_dir"
work_dir=""
for basis in DZ TZ; do
    for spin in Singlet Triplet; do
        branch="$ROOT_DIR/Columbus/$basis/$diradical/$spin"
        mkdir -p "$branch/MCSCF" "$branch/CISD" "$branch/AQCC" \
            "$branch/MCSCF-prep" "$branch/CISD-prep" "$branch/AQCC-prep"
    done
done

echo "Initialized $diradical: $state_dir"